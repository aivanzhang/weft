"""Freeze compact local evidence; omit large binaries and inert bytecode explicitly."""
import hashlib,json,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
HERE=Path(__file__).resolve().parent
OUT=ROOT/'evidence/fringe-allocation-and-sampler-v1'
SOURCES=[
'outputs/edge-fringe-allocation-census-v1','outputs/fringe-allocation-analytic-v1',
'outputs/fringe-allocation-analytic-v2','outputs/edge-fringe-area-candidate-preparation-v1',
'outputs/panda-edge-fringe-area-v1','outputs/edge-fringe-area-preview-preparation-v1',
'outputs/panda-edge-fringe-area-preview-v1','outputs/panda-edge-fringe-area-review-v1',
'outputs/panda-edge-fringe-area-audit-v1','outputs/root-color-sampler-review-v1',
'outputs/root-color-sampler-guard-tests-v1','outputs/root-sampler-integration-tests-v1',
'outputs/root-sampler-loopback-tests-v1','outputs/fringe-allocation-save-v1']
def sha(path):
 h=hashlib.sha256()
 with path.open('rb') as stream:
  for chunk in iter(lambda:stream.read(1024*1024),b''):h.update(chunk)
 return h.hexdigest()
files=[]
for folder in SOURCES:
 for path in sorted((ROOT/folder).rglob('*')):
  assert not path.is_symlink(),path
  if path.is_file():files.append(path)
assert len(files)<=512
rows=[];omitted=[];objects={};total=0
for path in files:
 size=path.stat().st_size
 assert size<=128*1024*1024,path
 row={'origin':str(path.relative_to(ROOT)),'bytes':size,'sha256':sha(path)}
 if size>2*1024*1024 or path.suffix in ('.glb','.blend','.pyc'):
  row['reason']='Large model/native file remains local; compact evidence is not a remote binary backup.' if path.suffix!='.pyc' else 'Generated bytecode omitted; exact Python source retained.'
  omitted.append(row);continue
 key=row['sha256']
 if key not in objects:
  objects[key]='payload/'+key+'/'+path.name
  total+=size
 row['saved_path']=objects[key];rows.append(row)
assert total<=16*1024*1024,(total,'bundle exceeds bound')
OUT.mkdir()
for row in rows:
 src=ROOT/row['origin'];dest=OUT/row['saved_path']
 assert sha(src)==row['sha256']
 if not dest.exists():
  dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,dest)
 assert sha(dest)==row['sha256']
