"""Generate packaged brand resources from the approved artwork and palette."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "assets" / "brand" / "source"
EXPORTS = SOURCE.parent / "exports"
DESTINATION = ROOT / "src" / "weft" / "assets"


def sync(check=False):
    palette_bytes = (SOURCE / "palette.json").read_bytes()
    palette = json.loads(palette_bytes)["colors"]
    required = {"primary", "primary_hover", "primary_foreground", "accent", "canvas",
                "surface", "ink", "muted", "border"}
    if set(palette) != required or any(not re.fullmatch(r"#[0-9A-F]{6}", value) for value in palette.values()):
        raise ValueError("Palette requires the documented roles and uppercase six-digit hex colors")
    declarations = ["  --weft-" + name.replace("_", "-") + ": " + value + ";"
                    for name, value in palette.items()]
    css = ("/* Generated by scripts/brand/sync_brand.py; edit assets/brand/source/palette.json. */\n"
           ":root {\n  color-scheme: light;\n" + "\n".join(declarations) + "\n}\n")
    outputs = {DESTINATION / "brand.css": css.encode(), DESTINATION / "palette.json": palette_bytes,
               DESTINATION / "weft-logo.png": (EXPORTS / "weft-logo.png").read_bytes(),
               EXPORTS / "palette.css": css.encode()}
    outputs[EXPORTS / "weft-mascot-sprites.json"] = (SOURCE / "weft-mascot-sprites.json").read_bytes()
    atlas = json.loads((SOURCE / "weft-mascot-sprites.json").read_text())
    outputs[EXPORTS / "weft-mascot-sprites.js"] = (
        "// Generated by scripts/brand/sync_brand.py; edit assets/brand/source/weft-mascot-sprites.json.\n"
        "window.WEFT_MASCOT_ATLAS = " + json.dumps(atlas, separators=(",", ":")) + ";\n").encode()
    changed = []
    for target, content in outputs.items():
        if not target.is_file() or target.read_bytes() != content:
            changed.append(str(target.relative_to(ROOT)))
            if not check:
                target.write_bytes(content)
    if check and changed:
        raise SystemExit("Stale packaged brand resources: " + ", ".join(changed))
    print("Brand resources are current" if not changed else "Updated: " + ", ".join(changed))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated resources without writing")
    sync(parser.parse_args().check)
